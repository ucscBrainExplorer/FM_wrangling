#!/usr/bin/env python3
"""
md_to_remap.py — convert a hand-curated CL reference markdown table to remap TSV.

Reads a markdown file whose reference table has the columns:
  | harmonized_cell_label | Cells | Suggested CL term | CL ID | Confidence | Notes |

and produces a remap TSV compatible with cellLabelMap_obs.py.

Usage
-----
  python3 md_to_remap.py \\
      --md  harmonized_cell_label_cl_reference.md \\
      --out obs_harmonized_remap.tsv \\
      [--source-col harmonized_cell_label]

Output columns (required by cellLabelMap_obs.py)
-------------------------------------------------
  original_label
  mapped_cell_label_ontology_term_id
  mapped_cell_label_ontology_term_name
  mapped_cell_label_ontology_term_match_method

Confidence → match method
-------------------------
  High   → reference_high
  Medium → reference_medium
  Low    → reference_low
"""

import argparse
import re
import sys
from datetime import datetime

import pandas as pd


CONF_TO_METHOD = {
    "high":   "reference_high",
    "medium": "reference_medium",
    "low":    "reference_low",
}

# Expected column positions in the reference table
COL_LABEL      = 0
COL_CL_TERM    = 2
COL_CL_ID      = 3
COL_CONFIDENCE = 4


def parse_md_table(md_path):
    """Parse the reference table rows from the markdown file.

    Returns list of dicts with the four remap columns.
    """
    rows = []
    header_found = False

    with open(md_path) as f:
        for line in f:
            line = line.rstrip('\n')
            if not line.startswith('|'):
                continue

            cells = [c.strip() for c in line.strip('|').split('|')]

            if not header_found:
                clean = [re.sub(r'`', '', c).strip() for c in cells]
                if 'harmonized_cell_label' in clean or 'CL ID' in clean:
                    header_found = True
                continue

            # Skip separator rows (|---|...)
            if all(re.match(r'^[-:]+$', c) for c in cells if c):
                continue

            if len(cells) <= COL_CONFIDENCE:
                continue

            label      = re.sub(r'`', '', cells[COL_LABEL]).strip()
            cl_term    = cells[COL_CL_TERM].strip()
            cl_id      = cells[COL_CL_ID].strip()
            confidence = cells[COL_CONFIDENCE].strip()

            if not label or not cl_id:
                continue

            rows.append({
                'original_label':                               label,
                'mapped_cell_label_ontology_term_id':           cl_id,
                'mapped_cell_label_ontology_term_name':         cl_term,
                'mapped_cell_label_ontology_term_match_method': CONF_TO_METHOD.get(
                    confidence.lower(), 'reference'),
            })

    return rows


def main():
    parser = argparse.ArgumentParser(
        description="Convert a hand-curated CL reference markdown to remap TSV"
    )
    parser.add_argument("--md", required=True,
                        help="Input markdown reference file")
    parser.add_argument("--out", required=True,
                        help="Output remap TSV path")
    parser.add_argument("--source-col", default="harmonized_cell_label",
                        help="Source column name written to remap header "
                             "(default: harmonized_cell_label)")
    args = parser.parse_args()

    rows = parse_md_table(args.md)
    if not rows:
        print(f"Error: no table rows parsed from {args.md}", file=sys.stderr)
        sys.exit(1)

    remap_df = pd.DataFrame(rows, columns=[
        'original_label',
        'mapped_cell_label_ontology_term_id',
        'mapped_cell_label_ontology_term_name',
        'mapped_cell_label_ontology_term_match_method',
    ])

    comment_lines = [
        "# Generated by md_to_remap.py",
        f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        f"# Input: {args.md}",
        f"# Source column: {args.source_col}",
    ]

    with open(args.out, 'w') as f:
        f.write('\n'.join(comment_lines) + '\n')
        remap_df.to_csv(f, sep='\t', index=False)

    method_counts = remap_df['mapped_cell_label_ontology_term_match_method'].value_counts()
    print(f"Written {len(remap_df)} rows to {args.out}")
    print(f"  Source column: {args.source_col}")
    for method, count in method_counts.items():
        print(f"  {method}: {count}")


if __name__ == "__main__":
    main()
